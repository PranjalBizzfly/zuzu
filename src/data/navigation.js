// Footer layout: five same-shaped middle columns (Product, Solutions,
// Industries, Platform, Resources) plus a narrower Company sidebar
// (Company / Security), derived from the same nav
// data so the footer can never drift out of sync with the header mega
// menus. A column is either a flat { heading, links } list, or a
// { heading, groups } list made of a couple of short labeled sub-lists.
export function getFooterGroups() {
  const productAndSolutions = NAV_SECTIONS.filter((s) => s.key === 'product' || s.key === 'solutions').map(
    (section) => ({
      heading: section.label,
      links: [
        ...section.items.map((item) => ({ label: item.label, href: `${section.href}/${item.slug}` })),
        { label: `All ${section.label}`, href: section.href },
      ],
    })
  )

  const industries = findSection('industries')
  const resources = findSection('resources')

  const columns = [
    ...productAndSolutions,
    {
      // Only the first 8 (the same set shown on the Landing Page Industries
      // section) so this column stays the same length as Product/Solutions
      // rather than listing all 32+ industries -- the rest render in the
      // dedicated FooterMoreIndustries grid instead (see Footer.jsx).
      heading: 'Industries',
      links: [
        ...industries.items.slice(0, 8).map((item) => ({ label: item.label, href: `/industries/${item.slug}` })),
        { label: 'All Industries', href: '/industries' },
        { label: 'Use Cases', href: '/use-cases' },
        { label: 'Roles', href: '/roles' },
      ],
    },
    { heading: 'Platform', links: PLATFORM_HUB_LINKS },
    {
      heading: 'How It Works',
      links: [
        ...HOW_IT_WORKS_SECTION.items.map((item) => ({
          label: item.label,
          href: `${HOW_IT_WORKS_SECTION.href}/${item.slug}`,
        })),
        { label: 'How It Works Overview', href: HOW_IT_WORKS_SECTION.href },
      ],
    },
    {
      heading: 'Dashboard',
      links: [
        { label: 'Team at a Glance', href: '/dashboard/team-at-a-glance' },
        { label: 'Manager Dashboard', href: '/dashboard/manager-dashboard' },
        { label: 'Employee Profile', href: '/dashboard/employee-profile' },
        { label: 'Admin Portal', href: '/dashboard/admin-portal' },
        { label: 'Super Admin Layer', href: '/dashboard/super-admin' },
        { label: 'Workforce Analytics', href: '/dashboard/workforce-analytics' },
        { label: 'Day-End Report', href: '/dashboard/day-end-report' },
      ],
    },
    {
      heading: 'Resources',
      groups: [
        {
          title: 'Resources',
          links: [
            ...resources.items.map((item) => ({ label: item.label, href: `/resources/${item.slug}` })),
            { label: 'All Resources', href: '/resources' },
          ],
        },
      ],
    },
  ]

  const sidebar = {
    heading: 'Company',
    groups: [
      { title: 'Company', links: COMPANY_LINKS },
      {
        title: 'Security',
        links: [
          { label: 'Security Overview', href: '/security' },
          { label: 'Screenshot + Privacy Ecosystem', href: '/screenshot-privacy' },
          { label: 'Admin Portal + Security & Governance', href: '/admin' },
        ],
      },
    ],
  }

  return { columns, sidebar }
}
